#!/bin/sh
# Regenerates src/diacritics.ts from kitty's Unicode placeholder row/column diacritics table.
set -e
curl -fsSL https://raw.githubusercontent.com/kovidgoyal/kitty/master/gen/rowcolumn-diacritics.txt |
	grep -v '^#' | cut -d';' -f1 | awk 'BEGIN { printf "/** Kitty Unicode placeholder row/column diacritics, generated by scripts/gen-diacritics.sh. */\nexport const DIACRITICS = [" } { printf "%s0x%s", (NR > 1 ? ", " : ""), $1 } END { print "];" }' > src/diacritics.ts
